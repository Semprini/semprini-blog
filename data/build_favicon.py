"""Generates app/static/images/favicon.{svg,ico} — the site icon.

Run from the repo root:  .venv/bin/python data/build_favicon.py

The mark is an "S" monogram on the blog's main colour (#546ba3). It is defined
here as geometry rather than as a glyph so the SVG and the ICO come out of one
description and cannot drift apart: no font has to be present to render it, and
there is no rasteriser in the toolchain to convert one format to the other.

The S is two circular arcs of equal radius whose ends meet, the upper one swept
anticlockwise and the lower one clockwise. Both cover 250 degrees, which is what
leaves the open bowls an S needs rather than a figure 8.
"""

import math
import pathlib

from PIL import Image, ImageDraw

BLUE = (84, 107, 163)          # #546ba3, the blog's --main-color
WHITE = (255, 255, 255)

BOX = 64                        # design grid; the SVG viewBox
RADIUS = 10                     # of each arc
STROKE = 8                      # pen width
CORNER = 12                     # rounding of the background tile
TOP = (32, 24)                  # upper bowl centre
BOTTOM = (32, 44)               # lower bowl centre

# Where the stroke starts and finishes, on the far side of each bowl.
START = (TOP[0] + RADIUS * math.cos(math.radians(340)),
         TOP[1] + RADIUS * math.sin(math.radians(340)))
END = (BOTTOM[0] + RADIUS * math.cos(math.radians(160)),
       BOTTOM[1] + RADIUS * math.sin(math.radians(160)))
JOIN = (32, 34)                 # bottom of the upper bowl == top of the lower

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "app" / "static" / "images"


def write_svg():
    path = (f"M {START[0]:.2f} {START[1]:.2f} "
            f"A {RADIUS} {RADIUS} 0 1 0 {JOIN[0]} {JOIN[1]} "
            f"A {RADIUS} {RADIUS} 0 1 1 {END[0]:.2f} {END[1]:.2f}")
    svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {BOX} {BOX}">
  <!-- Generated by data/build_favicon.py - edit that, not this. -->
  <rect width="{BOX}" height="{BOX}" rx="{CORNER}" fill="#546ba3"/>
  <path d="{path}" fill="none" stroke="#fff" stroke-width="{STROKE}"
        stroke-linecap="round"/>
</svg>
'''
    (OUT / "favicon.svg").write_text(svg)


def render(size):
    """Draws the mark at 4x and downsamples, which is the antialiasing."""
    scale = 4
    px = size * scale
    k = px / BOX
    img = Image.new("RGBA", (px, px), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    d.rounded_rectangle([0, 0, px - 1, px - 1], radius=CORNER * k, fill=BLUE)

    def bbox(centre):
        cx, cy = centre[0] * k, centre[1] * k
        r = RADIUS * k
        return [cx - r, cy - r, cx + r, cy + r]

    w = max(1, round(STROKE * k))
    # Pillow sweeps clockwise from start to end, so the upper bowl's
    # anticlockwise 340->90 is expressed as 90->340.
    d.arc(bbox(TOP), start=90, end=340, fill=WHITE, width=w)
    d.arc(bbox(BOTTOM), start=270, end=520, fill=WHITE, width=w)

    # Pillow's arc has no line cap, so the ends and the join get a disc each.
    for x, y in (START, JOIN, END):
        r = w / 2
        d.ellipse([x * k - r, y * k - r, x * k + r, y * k + r], fill=WHITE)

    return img.resize((size, size), Image.LANCZOS)


def write_ico():
    # Each size is drawn at its own scale rather than downscaled from one
    # bitmap, so the 16px stroke stays crisp. Pillow keys the frames off the
    # base image and will not upscale past it, so the largest goes first.
    sizes = [48, 32, 16]
    frames = [render(s) for s in sizes]
    frames[0].save(OUT / "favicon.ico", format="ICO",
                   sizes=[(s, s) for s in sizes], append_images=frames[1:])


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    write_svg()
    write_ico()
    print(f"wrote {OUT/'favicon.svg'} and {OUT/'favicon.ico'}")
